"""Scaffold a new robot: ``python scripts/tools/new_robot.py <vendor> <model> <variant>``.

One command creates every file a new robot needs, each filled with TODO
placeholders and pointers to a worked example (the AgiBot X2 files, which were
built from scratch against vendor assets and document their provenance line by
line):

- ``source/yanshi_rl_lab/yanshi_rl_lab/robots/<vendor>/<model>/<variant>/{__init__.py, profile.py}``
- ``source/.../tasks/locomotion/velocity/config/<vendor>/<model>/<variant>/__init__.py``
- ``tests/test_<model>_<variant>_profile.py``

Missing vendor- and model-level ``__init__.py`` files are created too, so a
second variant of an existing model adds one directory and touches nothing
shared. Existing variant files are NEVER overwritten: the script refuses and
exits non-zero.

The ``<variant>`` segment is mandatory. It is upstream's own name for the
configuration (``dof29`` for a model published as ``g1_29dof``, ``v1_4_0`` for
a directory named ``X2_URDF-v1.4.0``) -- never invented here -- and it must
start with a letter because it is also a Python package name.

Design notes (why the scaffold looks the way it does):

- The generated ``profile.py`` starts with a module-level ``raise`` so that a
  half-filled profile can never be imported silently. Every value is a ``TODO``
  sentinel, never a plausible-looking number -- inventing robot facts is banned
  in this repository.
- The generated task registration is commented out: ``yanshi_rl_lab.tasks``
  imports every config package on startup, so a live registration call against
  an unfinished profile would take down every task in the framework.
- The generated test module skips itself while the profile scaffold is
  unfilled, keeping the suite green right after scaffolding.
"""

