def _render(template: str, vendor: str, model: str, variant: str) -> str:
    year = datetime.date.today().year
    return template.format(
        header=_HEADER.format(year=year).rstrip("\n"),
        vendor=vendor,
        model=model,
        variant=variant,
        vendor_title=vendor.replace("_", " ").title(),
        profile_name=f"{model.upper()}_{variant.upper()}_PROFILE",
        test_stem=f"{model}_{variant}",
        date=datetime.date.today().isoformat(),
    )


def _plan_files(repo_root: Path, vendor: str, model: str, variant: str) -> dict[Path, str]:
    """Map of target path -> rendered content, variant-level files only."""
    pkg = repo_root / "source" / "yanshi_rl_lab" / "yanshi_rl_lab"
    robots = pkg / "robots" / vendor / model / variant
    config = pkg / "tasks" / "locomotion" / "velocity" / "config" / vendor / model / variant
    return {
        robots / "__init__.py": _render(_ROBOT_VARIANT_INIT, vendor, model, variant),
        robots / "profile.py": _render(_ROBOT_PROFILE, vendor, model, variant),
        config / "__init__.py": _render(_CONFIG_VARIANT_INIT, vendor, model, variant),
        repo_root / "tests" / f"test_{model}_{variant}_profile.py": _render(
            _TEST_MODULE, vendor, model, variant
        ),
    }


def _plan_parent_inits(repo_root: Path, vendor: str, model: str, variant: str) -> dict[Path, str]:
    """Vendor- and model-level ``__init__.py`` files, created only when missing.

    A second variant of an already-registered model therefore adds exactly one
    directory and touches nothing shared.
    """
    pkg = repo_root / "source" / "yanshi_rl_lab" / "yanshi_rl_lab"
    config = pkg / "tasks" / "locomotion" / "velocity" / "config"
    return {
        pkg / "robots" / vendor / "__init__.py": _render(_ROBOT_VENDOR_INIT, vendor, model, variant),
        pkg / "robots" / vendor / model / "__init__.py": _render(
            _ROBOT_MODEL_INIT, vendor, model, variant
        ),
        config / vendor / "__init__.py": _render(_CONFIG_VENDOR_INIT, vendor, model, variant),
        config / vendor / model / "__init__.py": _render(_CONFIG_MODEL_INIT, vendor, model, variant),
    }


def scaffold(repo_root: Path, vendor: str, model: str, variant: str) -> list[Path]:
    """Create all scaffold files; refuse to touch anything that exists."""
    for name, value in (("vendor", vendor), ("model", model), ("variant", variant)):
        if not NAME_RE.match(value):
            raise SystemExit(
                f"{name} {value!r} is invalid: use lowercase letters, digits and "
                "underscores, starting with a letter (e.g. 'unitree', 'humanoid_lite', "
                "'dof29'). A leading digit would not be an importable package name -- "
                "write 'dof29', not '29dof'."
            )

    files = _plan_files(repo_root, vendor, model, variant)
    existing = [p for p in files if p.exists()]
    if existing:
        listing = "\n  ".join(str(p.relative_to(repo_root)) for p in existing)
        raise SystemExit(
            f"Refusing to overwrite existing files for {vendor}/{model}/{variant}:\n  {listing}\n"
            "Delete them yourself first if you really mean to re-scaffold."
        )

    created: list[Path] = []
    for path, content in _plan_parent_inits(repo_root, vendor, model, variant).items():
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            created.append(path)
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        created.append(path)
    return created


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("vendor", help="vendor name, lowercase_with_underscores (e.g. unitree)")
    parser.add_argument("model", help="model name, lowercase_with_underscores (e.g. g1, humanoid_lite)")
    parser.add_argument(
        "variant",
        help="configuration name, UPSTREAM'S OWN (e.g. dof29, v1_4_0, humanoid). "
        "Must start with a letter -- it is a package name, so write 'dof29', not '29dof'.",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=_REPO_ROOT,
        help="repository root to scaffold into (default: this script's repo; overridable for tests)",
    )
    args = parser.parse_args()

    created = scaffold(args.repo_root.resolve(), args.vendor, args.model, args.variant)
    key = f"{args.vendor}/{args.model}/{args.variant}"
    print(f"Scaffolded robot {key}:")
    for path in created:
        print(f"  created  {path.relative_to(args.repo_root.resolve())}")
    print(
        "\nNext steps:\n"
        f"  1. Assets: if {args.vendor}/{args.model} is NOT yet in assets/registry.py, add it\n"
        f"     (pinned commit + license) and run: python assets/fetch.py {args.vendor}/{args.model}\n"
        "     If another variant of this model is already registered, the assets are\n"
        "     already fetched -- variants share one asset tree, do NOT add a second key.\n"
        f"  2. Fill in robots/{args.vendor}/{args.model}/{args.variant}/profile.py\n"
        "     (every TODO, with sources), then delete its guard raise.\n"
        "  3. Uncomment the registration call in the velocity config package.\n"
        f"  4. Flesh out tests/test_{args.model}_{args.variant}_profile.py and run pytest.\n"
        "  5. Add a gate file under benchmark/gates/ before the first training run\n"
        "     (pre-registration discipline: gates are frozen before the run they judge)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
